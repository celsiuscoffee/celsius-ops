import { useCallback, useState } from "react";
import {
  ActivityIndicator,
  FlatList,
  Pressable,
  RefreshControl,
  Text,
  View,
} from "react-native";
import { useFocusEffect, useRouter } from "expo-router";
import { Screen } from "../../../components/Screen";
import { PageHeader } from "../../../components/PageHeader";
import {
  AlertCircle,
  CheckCircle2,
  ChevronRight,
  ClipboardCheck,
  ClipboardList,
  Clock,
} from "lucide-react-native";
import { useStaff } from "../../../lib/store";
import { hasAccess } from "../../../lib/access";
import { List, ListRow, Segmented } from "../../../components/ui";
import {
  generateChecklists,
  listChecklists,
  type ChecklistShift,
  type ChecklistSummary,
} from "../../../lib/ops/checklists";
import { useCelsius } from "../../../lib/celsius-ui";

const SHIFT_LABEL: Record<ChecklistShift, string> = {
  OPENING: "Opening",
  MIDDAY: "Midday",
  CLOSING: "Closing",
};

const SHIFT_ORDER: ChecklistShift[] = ["OPENING", "MIDDAY", "CLOSING"];

export default function ChecklistsList() {
  const C = useCelsius().color;
  const router = useRouter();
  const session = useStaff((s) => s.session);
  const [items, setItems] = useState<ChecklistSummary[]>([]);
  const [loading, setLoading] = useState(true);
  const [refreshing, setRefreshing] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [autoGenerated, setAutoGenerated] = useState(false);
  const [scope, setScope] = useState<"mine" | "all">("mine");

  const today = todayString();

  const load = useCallback(
    async (silent = false) => {
      if (!session?.outletId) {
        setItems([]);
        setLoading(false);
        return;
      }
      if (!silent) setLoading(true);
      setError(null);
      try {
        const data = await listChecklists({
          date: today,
          outletId: session.outletId,
        });
        if (data.length === 0 && !autoGenerated) {
          setAutoGenerated(true);
          try {
            await generateChecklists({
              outletId: session.outletId,
              date: today,
            });
            const after = await listChecklists({
              date: today,
              outletId: session.outletId,
            });
            setItems(after);
          } catch {
            setItems([]);
          }
        } else {
          setItems(data);
        }
      } catch (e) {
        setError(e instanceof Error ? e.message : "Couldn't load");
      } finally {
        setLoading(false);
        setRefreshing(false);
      }
    },
    [session?.outletId, today, autoGenerated],
  );

  useFocusEffect(
    useCallback(() => {
      load(true);
    }, [load]),
  );

  // "Mine" = shared whole-outlet tasks (opening/closing/cleaning, everyone's
  // job), checklists assigned to me, ones I've already ticked items on, or
  // unassigned ("Anyone") ones I can pick up; it hides only checklists assigned
  // to someone else that I haven't touched. Default view so staff land on their
  // own work, with an "All" toggle for the full outlet board.
  const myId = session?.userId ?? null;
  const isMine = (c: ChecklistSummary) =>
    c.shared ||
    !c.assignedTo ||
    c.assignedTo.id === myId ||
    (c.myCompletedItems ?? 0) > 0;
  const mineCount = items.filter(isMine).length;
  const visible = scope === "all" ? items : items.filter(isMine);

  const grouped = SHIFT_ORDER.map((shift) => ({
    shift,
    items: visible.filter((c) => c.shift === shift),
  })).filter((g) => g.items.length > 0);

  const completed = items.filter((c) => c.status === "COMPLETED").length;
  const total = items.length;
  const pct = total > 0 ? Math.round((completed / total) * 100) : 0;

  // Personal contribution across every checklist today, sum of
  // items the calling user has marked done divided by the total
  // possible items across all checklists. Surfaces the "you did X
  // of Y" number staff care about (vs the team-level X/Y above).
  const myItems = items.reduce((s, c) => s + (c.myCompletedItems ?? 0), 0);
  const totalItemCount = items.reduce((s, c) => s + c.totalItems, 0);

  // Checks = today's checklists, with audits one row away (the old Audit tab
  // repeated this screen's job for the same people).
  const canAudit = hasAccess(session?.role, session?.moduleAccess, "ops:audit");
  const auditsRow = canAudit ? (
    <View className="mb-4">
      <List>
        <ListRow
          icon={ClipboardList}
          title="Audits"
          meta="Spot checks and quality audits"
          onPress={() => router.push("/audit")}
        />
      </List>
    </View>
  ) : null;

  return (
    <Screen edges={["top", "left", "right"]}>
      <PageHeader title="Checks" subtitle={dateLabel()} />
      {loading && items.length === 0 ? (
        <View className="flex-1 items-center justify-center">
          <ActivityIndicator color={C["text-3"]} />
        </View>
      ) : error ? (
        <View className="flex-1 items-center justify-center px-6">
          <Text className="text-sm text-danger-text text-center">{error}</Text>
        </View>
      ) : (
        <FlatList
          data={grouped}
          keyExtractor={(g) => g.shift}
          contentContainerClassName="pt-2 pb-6"
          refreshControl={
            <RefreshControl
              refreshing={refreshing}
              onRefresh={() => {
                setRefreshing(true);
                load(true);
              }}
              tintColor={C["text-3"]}
            />
          }
          ListHeaderComponent={
            <View>
              {/* Progress card, team progress on top (checklists
                  fully completed) + personal contribution below
                  (items the calling user has ticked off across every
                  checklist today). */}
              {auditsRow}
              {total > 0 ? (
                <View className="mb-4 rounded-2xl border border-line bg-surface px-4 py-3.5">
                  <View className="flex-row items-center justify-between">
                    <Text className="text-base font-body-semi text-text">Team progress</Text>
                    <Text className="text-sm font-body-semi text-text-2" style={{ fontVariant: ["tabular-nums"] }}>
                      {completed} of {total} done
                    </Text>
                  </View>
                  <View className="mt-2 h-2 overflow-hidden rounded-full bg-sunken">
                    <View
                      className={`h-full ${pct === 100 ? "bg-ok" : "bg-ink"}`}
                      style={{ width: `${pct}%` }}
                    />
                  </View>
                  <View className="mt-3 flex-row items-center justify-between border-t border-line pt-3">
                    <Text className="text-sm font-body text-text-2">Your part</Text>
                    <Text className="text-sm font-body-semi text-text" style={{ fontVariant: ["tabular-nums"] }}>
                      {myItems} of {totalItemCount} items
                    </Text>
                  </View>
                </View>
              ) : null}
              {total > 0 ? (
                <View className="mb-4">
                  <Segmented
                    options={[
                      { key: "mine", label: `Mine · ${mineCount}` },
                      { key: "all", label: `All · ${total}` },
                    ]}
                    value={scope}
                    onChange={setScope}
                  />
                </View>
              ) : null}
            </View>
          }
          ListEmptyComponent={
            <View className="mt-12 items-center px-6">
              <View className="h-20 w-20 items-center justify-center rounded-2xl bg-sunken">
                <ClipboardCheck color={C["text-2"]} size={32} />
              </View>
              <Text className="mt-4 text-base font-display text-text">
                {total > 0 && scope === "mine"
                  ? "Nothing assigned to you"
                  : "No checklists today"}
              </Text>
              <Text className="mt-1 text-sm font-body text-text-2 text-center">
                {total > 0 && scope === "mine"
                  ? "Tap All to see the team's checklists."
                  : "Checklists scheduled for this outlet show here."}
              </Text>
              {total > 0 && scope === "mine" ? (
                <Pressable
                  onPress={() => setScope("all")}
                  accessibilityRole="button"
                  className="mt-4 h-11 justify-center rounded-xl bg-ink px-5 active:opacity-80"
                >
                  <Text className="text-sm font-body-semi text-on-ink">
                    Show all
                  </Text>
                </Pressable>
              ) : null}
            </View>
          }
          ItemSeparatorComponent={() => <View className="h-4" />}
          renderItem={({ item: group }) => (
            <View>
              <Text accessibilityRole="header" className="mb-2 text-sm font-body-semi text-text-2">
                {SHIFT_LABEL[group.shift]} shift
              </Text>
              <View className="gap-2">
                {group.items.map((cl) => (
                  <ChecklistRow
                    key={cl.id}
                    cl={cl}
                    onPress={() => router.push(`/checklists/${cl.id}`)}
                  />
                ))}
              </View>
            </View>
          )}
      showsVerticalScrollIndicator={false}
    />
      )}
    </Screen>
  );
}

function ChecklistRow({
  cl,
  onPress,
}: {
  cl: ChecklistSummary;
  onPress: () => void;
}) {
  const C = useCelsius().color;
  const Icon =
    cl.status === "COMPLETED"
      ? CheckCircle2
      : cl.status === "IN_PROGRESS"
        ? AlertCircle
        : Clock;
  const iconColor =
    cl.status === "COMPLETED"
      ? C["ok-text"]
      : cl.status === "IN_PROGRESS"
        ? C["info-text"]
        : C["warn-text"];
  const bg =
    cl.status === "COMPLETED"
      ? "bg-ok-soft"
      : cl.status === "IN_PROGRESS"
        ? "bg-info-soft"
        : "bg-warn-soft";

  return (
    <Pressable
      onPress={onPress}
      accessibilityRole="button"
      className="min-h-[60px] rounded-2xl border border-line bg-surface px-3 py-2.5 active:bg-sunken"
    >
      <View className="flex-row items-center gap-3">
        <View
          className={`h-10 w-10 items-center justify-center rounded-xl ${bg}`}
        >
          <Icon color={iconColor} size={16} />
        </View>
        <View className="flex-1">
          <Text
            className="text-base font-body-medium text-text"
            numberOfLines={1}
          >
            {cl.sop.title}
          </Text>
          <Text className="text-sm font-body text-text-3" numberOfLines={1}>
            {cl.sop.category.name} · {cl.completedItems} of {cl.totalItems}
            {cl.myCompletedItems > 0 ? ` · ${cl.myCompletedItems} by you` : ""}
            {cl.shared
              ? " · Shared"
              : cl.assignedTo
                ? ` · ${cl.assignedTo.name}`
                : " · Anyone"}
          </Text>
        </View>
        <View className="items-end">
          <Text className="text-base font-body-bold text-text">
            {cl.progress}%
          </Text>
        </View>
        <ChevronRight color={C["text-3"]} size={16} />
      </View>
      <View className="mt-2 h-1 overflow-hidden rounded-full bg-sunken">
        <View
          className={`h-full ${cl.status === "COMPLETED" ? "bg-ok" : "bg-ink"}`}
          style={{ width: `${cl.progress}%` }}
        />
      </View>
    </Pressable>
  );
}

function todayString(): string {
  const d = new Date(Date.now() + 8 * 60 * 60 * 1000);
  return d.toISOString().split("T")[0];
}

function dateLabel(): string {
  return new Date().toLocaleDateString([], {
    weekday: "long",
    day: "numeric",
    month: "short",
  });
}
